#!/usr/bin/env python3
"""Turn gremlins' and Stryker's JSON reports into one pull request comment.

Both tools run only on the lines a pull request changes. The comment lists the
mutants that survived (a test ran the line but no test failed when it changed) and
counts, per file, the mutants no test reaches. Generated code is left out: a pull
request that regenerates a client changes thousands of lines nobody wrote. It is a
report: it never fails the build.

    mutation_report.py --gremlins gremlins.json --stryker a.json --stryker b.json \
        --go-root . --web-root web --out comment.md

A report that is absent counts as no mutants, so a repository with only Go or
only TypeScript passes one flag. A tool that crashed also leaves no report, so the
workflow names it with --failed, and the comment says so instead of claiming every
mutant was caught.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

# The comment is found again by this line, so a later run edits it instead of adding another.
MARKER = "<!-- mutation-report -->"

# How many survivors and files the comment lists before it says how many more there are.
MOST_SURVIVORS = 30
MOST_FILES = 15

# What generators write at the top of a file: Go's convention, and hey-api's and sqlc's own.
GENERATED = ("code generated", "auto-generated", "autogenerated", "do not edit")


@dataclass(frozen=True, order=True)
class Mutant:
    file: str
    line: int
    mutator: str


def from_gremlins(report: dict) -> tuple[list[Mutant], list[Mutant]]:
    """The mutants gremlins found LIVED, and those NOT COVERED."""
    survived: list[Mutant] = []
    unreached: list[Mutant] = []
    for f in report.get("files") or []:
        for m in f.get("mutations") or []:
            mutant = Mutant(f["file_name"], m["line"], m["type"])
            if m["status"] == "LIVED":
                survived.append(mutant)
            elif m["status"] == "NOT COVERED":
                unreached.append(mutant)
    return survived, unreached


def from_stryker(report: dict) -> tuple[list[Mutant], list[Mutant]]:
    """The mutants Stryker marked Survived, and those with NoCoverage."""
    survived: list[Mutant] = []
    unreached: list[Mutant] = []
    for path, f in (report.get("files") or {}).items():
        for m in f.get("mutants") or []:
            mutant = Mutant(path, m["location"]["start"]["line"], m["mutatorName"])
            if m["status"] == "Survived":
                survived.append(mutant)
            elif m["status"] == "NoCoverage":
                unreached.append(mutant)
    return survived, unreached


def stryker_worked(report: dict) -> bool:
    """Whether Stryker's results can be trusted: it switched mutants on, which shows as tests
    recorded against them or as a mutant a test killed, and ran a test against every mutant it
    calls survived. A runner that cannot switch mutants on reads every mutant as survived."""
    mutants = [m for f in (report.get("files") or {}).values() for m in f.get("mutants") or []]
    if not mutants:
        return True
    switched_on = any(m.get("coveredBy") or m["status"] in ("Killed", "Timeout") for m in mutants)
    untested = any(m["status"] == "Survived" and not m.get("testsCompleted") for m in mutants)
    return switched_on and not untested


def generated(path: Path) -> bool:
    """Whether a file says in its first lines that a generator wrote it."""
    try:
        with path.open(encoding="utf-8", errors="replace") as f:
            head = "".join(f.readline() for _ in range(5)).lower()
    except OSError:
        return False
    return any(marker in head for marker in GENERATED)


def written(mutants: list[Mutant], root: str) -> list[Mutant]:
    """The mutants in files people write, the paths read against the tool's own directory."""
    return [m for m in mutants if not generated(Path(root) / m.file)]


def _table(mutants: list[Mutant]) -> list[str]:
    rows = ["| where | mutation |", "|---|---|"]
    rows += [f"| `{m.file}:{m.line}` | {m.mutator} |" for m in sorted(mutants)[:MOST_SURVIVORS]]
    if len(mutants) > MOST_SURVIVORS:
        rows += ["", f"…and {len(mutants) - MOST_SURVIVORS} more: see the job summary."]
    return rows


def _per_file(mutants: list[Mutant]) -> list[str]:
    counts = sorted(Counter(m.file for m in mutants).items(), key=lambda item: (-item[1], item[0]))
    rows = ["| file | mutants |", "|---|---|"]
    rows += [f"| `{path}` | {n} |" for path, n in counts[:MOST_FILES]]
    if len(counts) > MOST_FILES:
        rows += ["", f"…and {len(counts) - MOST_FILES} more files."]
    return rows


def render(
    survived: list[Mutant], unreached: list[Mutant], problems: list[str] | None = None, failed: list[str] | None = None
) -> str:
    lines = [MARKER, "### Mutation report", ""]
    if survived:
        noun = "mutant" if len(survived) == 1 else "mutants"
        lines += [
            f"{len(survived)} {noun} survived on the changed lines: a test ran the line, and no test failed "
            "when it changed. Each is a check a test is missing.",
            "",
            *_table(survived),
        ]
    elif not failed:
        lines.append("Every mutant on the changed lines was caught by a test.")
    for tool in failed or []:
        lines += ["", f"{tool} did not finish, so its mutants are not listed: see the job log."]
    if unreached:
        noun = "mutant" if len(unreached) == 1 else "mutants"
        lines += ["", f"#### No test reaches {len(unreached)} {noun} on the changed lines", "", *_per_file(unreached)]
    for problem in problems or []:
        lines += ["", f"- {problem}"]
    lines += ["", "This report never fails the build."]
    return "\n".join(lines) + "\n"


def _read(path: str | None, name: str, problems: list[str]) -> dict:
    if not path or not Path(path).is_file():
        return {}
    try:
        return json.loads(Path(path).read_text())
    except ValueError:
        problems.append(f"The {name} report could not be read, so its mutants are not listed.")
        return {}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Turn mutation reports into one pull request comment.")
    parser.add_argument("--gremlins", help="gremlins' JSON report (--output)")
    parser.add_argument("--stryker", action="append", default=[], help="a Stryker JSON report; one per run")
    parser.add_argument("--go-root", default=".", help="the directory gremlins' paths are relative to")
    parser.add_argument("--web-root", default=".", help="the directory Stryker's paths are relative to")
    parser.add_argument("--out", required=True, help="where to write the comment")
    parser.add_argument("--failed", action="append", default=[], help="a tool whose run did not finish")
    args = parser.parse_args(argv)

    problems: list[str] = []
    g_survived, g_unreached = from_gremlins(_read(args.gremlins, "gremlins", problems))
    stryker = {"files": {}}
    for path in args.stryker:
        stryker["files"].update(_read(path, "Stryker", problems).get("files") or {})
    s_survived, s_unreached = from_stryker(stryker)
    if not stryker_worked(stryker):
        s_survived, s_unreached = [], []
        args.failed.append("Stryker")
        problems.append(
            "Stryker ran no test against its mutants, so it could not switch them on: its "
            "survivors would all be false."
        )
    survived = written(g_survived, args.go_root) + written(s_survived, args.web_root)
    unreached = written(g_unreached, args.go_root) + written(s_unreached, args.web_root)
    comment = render(survived, unreached, problems, args.failed)
    Path(args.out).write_text(comment)
    print(comment)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
