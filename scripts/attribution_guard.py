#!/usr/bin/env python3
"""Fail a pull request that credits an AI agent, model or model provider.

Owner decision 2026-11-09: commits and pull requests credit the owner and automation that is not
an AI agent; any AI agent or model provider is always refused. For the pull request's author,
title and body, and for every commit in the range:

- each commit's author and every Co-Authored-By trailer must be an allowed identity: the owner
  (one of the owner's names with one of the owner's emails), reviewed automation, a GitHub App
  bot whose name carries no AI name, or, when non_owner_humans is "allow", a person whose name
  and email name no AI. An AI provider's address is never allowed;
- no line may carry a credit to an AI ("Generated by Mistral Vibe.", "Reviewed by Kimi K2.7"); a
  line-leading "generated with/by" banner that does not name an allowed generator such as
  Renovate or Release Please; a trailer whose key names an AI (Claude-Session:) or whose -by
  value is one; the robot emoji, outside Renovate's checkbox lines; an AI provider's email
  address; or a Claude Code link.

The identities, AI names and provider domains live in data/attribution-identities.json.

    attribution_guard.py [--title T] [--body B] [--pr-author LOGIN] [--range BASE..HEAD] [--identities FILE]

The title, body and author fall back to PR_TITLE, PR_BODY and PR_AUTHOR in the environment, which
is how the reusable workflow passes them without quoting them through a shell.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

DEFAULT_IDENTITIES = Path(__file__).resolve().parents[1] / "data" / "attribution-identities.json"

CO_AUTHOR = re.compile(r"^\s*co-authored-by:\s*(.*)$", re.IGNORECASE)
IDENTITY = re.compile(r"^(?P<name>[^<>]*?)\s*<(?P<email>[^<>\s]+)>\s*$")
# A GitHub App's commit address, with or without the numeric id GitHub prefixes it with.
BOT_ADDRESS = re.compile(r"^(?:\d+\+)?(?P<slug>[a-z0-9][a-z0-9-]*)\[bot\]@users\.noreply\.github\.com$")
# A credit names its subject straight after the verb: "Generated by Mistral Vibe.", "Reviewed by
# Kimi K2.7 and Qwen 3.8 Flash". The tail ends at a clause break, so prose that only mentions a
# "Generated with" line and names a provider later in the sentence is not a credit.
CREDIT = re.compile(
    r"\b(?:generated|written|reviewed|authored|co-authored|drafted|created|coded|produced|assisted|made"
    r"|implemented|planned)\s+(?:by|with|through|using|via)\b(?P<tail>[^,;\"`]{0,80})",
    re.IGNORECASE,
)
CLAUSE_END = re.compile(r"\.(?:\s|$)")
# A banner is a line of its own: "Generated with ...", "🤖 Generated by ...", "This PR was generated by ...".
# A line that opens on a quote only quotes one.
BANNER = re.compile(
    r"^[^a-z0-9\"'`]*(?:this\s+(?:pr|pull request|commit|change)\s+(?:was|has been)\s+)?generated\s+(?:with|by)\b",
    re.IGNORECASE,
)
# A git trailer's key in its hyphenated form, such as Claude-Session.
TRAILER_KEY = re.compile(r"^\s*(?P<key>[A-Za-z0-9]+(?:-[A-Za-z0-9]+)+):\s")
ROBOT = "\N{ROBOT FACE}"
# Renovate's own checkboxes, such as "- [ ] <!-- manual-job -->🤖 Pick PR", carry a comment marker.
RENOVATE_CHECKBOX = re.compile(r"^\s*[-*]\s+\[[ xX]\]\s*<!--")
EMAIL = re.compile(r"[a-z0-9._%+-]+@(?P<domain>[a-z0-9-]+(?:\.[a-z0-9-]+)+)", re.IGNORECASE)
CLAUDE_CODE_LINK = re.compile(r"claude\.(?:ai|com)/(?:claude-)?code\b", re.IGNORECASE)
# Names this long are matched inside a bot's name; shorter ones (gpt, pi) only as a whole part.
SUBSTRING_LENGTH = 5


def _words(names: tuple[str, ...]) -> re.Pattern[str]:
    """A whole-word match of any name; gpt matches gpt-5 and claude's, pi does not match pipeline."""
    return re.compile(r"(?<![a-z0-9])(" + "|".join(map(re.escape, names)) + r")(?![a-z])", re.IGNORECASE)


@dataclass(frozen=True)
class Policy:
    names: frozenset[str]
    emails: frozenset[str]
    automation: tuple[tuple[str, str | None], ...]
    allow_other_humans: bool
    ai_names: tuple[str, ...]
    person_only: tuple[str, ...]
    person_exempt: frozenset[str]
    provider_domains: tuple[str, ...]
    provider_labels: frozenset[str]
    generators: tuple[str, ...]

    @classmethod
    def load(cls, path: Path) -> Policy:
        data = json.loads(path.read_text(encoding="utf-8"))
        mode = data["non_owner_humans"]["mode"]
        if mode not in ("allow", "refuse"):
            raise ValueError(f'non_owner_humans.mode must be "allow" or "refuse", not "{mode}"')
        ai = data["ai_names"]
        return cls(
            names=frozenset(name.casefold() for name in data["people"]["names"]),
            emails=frozenset(email.casefold() for email in data["people"]["emails"]),
            automation=tuple(
                (entry["name"].casefold(), entry["email"].casefold() if "email" in entry else None)
                for entry in data["automation"]["identities"]
            ),
            allow_other_humans=mode == "allow",
            ai_names=tuple(name.casefold() for name in ai["names"]),
            person_only=tuple(name.casefold() for name in ai["person_only"]),
            person_exempt=frozenset(name.casefold() for name in ai["person_exempt"]),
            provider_domains=tuple(domain.casefold() for domain in data["provider_email_domains"]),
            provider_labels=frozenset(label.casefold() for label in data["provider_domain_labels"]),
            generators=tuple(generator.casefold() for generator in data["generators"]),
        )

    def ai_word(self, text: str, person: bool = False) -> str | None:
        """The first AI name in text as a whole word; in a person's name, the names people carry are
        skipped and the person-only words added."""
        names = self.ai_names
        if person:
            names = tuple(name for name in names if name not in self.person_exempt) + self.person_only
        found = _words(names).search(text)
        return found.group(1).casefold() if found else None

    def bot_ai_name(self, slug: str) -> str | None:
        """The AI name in a bot's name: inside it for a long name, as a whole part for a short one."""
        slug = slug.casefold()
        for name in self.ai_names:
            if len(name) >= SUBSTRING_LENGTH and name in slug:
                return name
        return self.ai_word(slug)

    def is_provider_domain(self, domain: str) -> bool:
        domain = domain.casefold()
        if any(domain == known or domain.endswith("." + known) for known in self.provider_domains):
            return True
        return any(label in self.provider_labels for label in domain.split("."))


def identity_refusal(name: str, email: str, policy: Policy) -> str | None:
    """Why name <email> may not be credited, or None when it is an allowed identity."""
    name = name.strip()
    folded_name, folded_email = name.casefold(), email.strip().casefold()
    if folded_email in policy.emails:
        if folded_name in policy.names:
            return None
        return f'"{name}" is not one of the owner\'s names'
    bot = BOT_ADDRESS.match(folded_email)
    if bot:
        slug = bot.group("slug")
        if (marker := policy.bot_ai_name(slug)) is not None:
            return f'{slug}[bot] is an AI agent\'s bot ("{marker}")'
        if folded_name == f"{slug}[bot]":
            return None
        return f'a bot address must carry its own name, {slug}[bot], not "{name}"'
    if policy.is_provider_domain(folded_email.rpartition("@")[2]):
        return f"<{email}> is an AI provider's address"
    for automation_name, automation_email in policy.automation:
        if folded_name == automation_name and automation_email in (None, folded_email):
            return None
    local = folded_email.partition("@")[0]
    marker = policy.ai_word(name, person=True) or policy.ai_word(local, person=True)
    if marker is not None:
        return f'{name} <{email}> names an AI ("{marker}")'
    if policy.allow_other_humans:
        return None
    return f"{name} <{email}> is not the owner, reviewed automation or an allowed GitHub App bot"


def author_refusal(login: str, policy: Policy) -> str | None:
    """Why a pull request's author login is an AI agent, or None."""
    bare = login.strip()
    if bare.startswith("app/") or bare.endswith("[bot]"):
        slug = bare.removeprefix("app/").removesuffix("[bot]")
        marker = policy.bot_ai_name(slug)
    else:
        marker = policy.ai_word(bare, person=True)
    return None if marker is None else f'{login} is an AI agent ("{marker}")'


def line_refusal(line: str, policy: Policy) -> str | None:
    """Why a line of a commit message, title or body credits an AI, or None."""
    co_author = CO_AUTHOR.match(line)
    if co_author:
        identity = IDENTITY.match(co_author.group(1).strip())
        if identity is None:
            return "a Co-Authored-By trailer that is not Name <email>"
        why = identity_refusal(identity.group("name"), identity.group("email"), policy)
        return None if why is None else f"a Co-Authored-By trailer credits someone not allowed: {why}"
    trailer = TRAILER_KEY.match(line)
    if trailer:
        key = trailer.group("key")
        if (marker := policy.ai_word(key.replace("-", " "))) is not None:
            return f'a trailer that names an AI ("{marker}")'
        if key.casefold().endswith("-by"):
            value = line[trailer.end():].strip()
            identity = IDENTITY.match(value)
            if identity is not None:
                why = identity_refusal(identity.group("name"), identity.group("email"), policy)
            else:
                marker = policy.ai_word(value, person=True)
                why = None if marker is None else f'"{value}" names an AI ("{marker}")'
            if why is not None:
                return f"a {key} trailer credits an AI: {why}"
    for credit in CREDIT.finditer(line):
        tail = CLAUSE_END.split(credit.group("tail"), maxsplit=1)[0]
        if (marker := policy.ai_word(tail)) is not None:
            return f'a credit to an AI ("{marker}")'
    if BANNER.match(line) and not any(generator in line.casefold() for generator in policy.generators):
        return 'a "generated with/by" banner'
    if ROBOT in line and not RENOVATE_CHECKBOX.match(line):
        return "the robot emoji"
    for email in EMAIL.finditer(line):
        if policy.is_provider_domain(email.group("domain")):
            return f"an AI provider's address <{email.group(0)}>"
    if CLAUDE_CODE_LINK.search(line):
        return "a Claude Code link"
    return None


def text_findings(text: str, policy: Policy) -> list[str]:
    """Every refused line of text, as "line N: why: the line"."""
    findings = []
    for number, line in enumerate(text.splitlines(), start=1):
        why = line_refusal(line, policy)
        if why is not None:
            findings.append(f"line {number}: {why}: {line.strip()}")
    return findings


@dataclass(frozen=True)
class Commit:
    sha: str
    author_name: str
    author_email: str
    message: str

    @property
    def label(self) -> str:
        subject = self.message.splitlines()[0] if self.message else ""
        return f'commit {self.sha[:12]} "{subject}"'


def commits_in(commit_range: str, repo: str = ".") -> list[Commit]:
    """Every commit in the range, newest first."""
    out = subprocess.run(
        ["git", "-C", repo, "log", "--format=%H%x1f%an%x1f%ae%x1f%B%x1e", commit_range],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    commits = []
    for record in out.split("\x1e"):
        record = record.lstrip("\n")
        if record:
            sha, name, email, message = record.split("\x1f", 3)
            commits.append(Commit(sha, name, email, message.strip("\n")))
    return commits


def check(title: str, body: str, commits: list[Commit], policy: Policy, pr_author: str = "") -> list[str]:
    """Every refusal in the author, the title, the body and the commits. Empty means clean."""
    failures = []
    if pr_author and (why := author_refusal(pr_author, policy)) is not None:
        failures.append(f"pull request author: {why}")
    failures += [f"pull request title: {finding}" for finding in text_findings(title, policy)]
    failures += [f"pull request body: {finding}" for finding in text_findings(body, policy)]
    for commit in commits:
        why = identity_refusal(commit.author_name, commit.author_email, policy)
        if why is not None:
            failures.append(f"{commit.label}: author {commit.author_name} <{commit.author_email}>: {why}")
        failures += [f"{commit.label}: message {finding}" for finding in text_findings(commit.message, policy)]
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Refuse a pull request that credits an AI agent.")
    parser.add_argument("--title", default=os.environ.get("PR_TITLE", ""))
    parser.add_argument("--body", default=os.environ.get("PR_BODY", ""))
    parser.add_argument("--pr-author", default=os.environ.get("PR_AUTHOR", ""))
    parser.add_argument("--range", dest="commit_range", help="BASE..HEAD, the pull request's commits")
    parser.add_argument("--identities", type=Path, default=DEFAULT_IDENTITIES)
    args = parser.parse_args(argv)

    policy = Policy.load(args.identities)
    commits = commits_in(args.commit_range) if args.commit_range else []
    failures = check(args.title, args.body, commits, policy, args.pr_author)
    for failure in failures:
        print(f"::error::{failure}")
    if failures:
        print(
            "\nCommits and pull requests credit no AI agent, model or provider. Remove the attribution "
            "(git rebase -i, then reword, or commit --amend --reset-author) and edit the title or body; "
            "who may be credited is in github-workflows data/attribution-identities.json."
        )
        return 1
    print(f"author, title, body and {len(commits)} commit(s) credit no AI")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
