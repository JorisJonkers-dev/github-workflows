from scripts.pr_title_check import attribution_findings, check, commit_messages, failure_reason, main


class ReadingATitle(unittest.TestCase):
    def test_a_typed_subject_is_accepted(self) -> None:
        self.assertIsNone(failure_reason("feat: add a workflow"))

    def test_a_scope_and_a_breaking_mark_are_accepted(self) -> None:
        self.assertIsNone(failure_reason("fix(ci/release)!: drop the old input"))

    def test_every_type_release_please_reads_is_accepted(self) -> None:
        for kind in ("feat", "fix", "docs", "style", "refactor", "perf", "test", "build", "ci", "chore", "revert"):
            self.assertIsNone(failure_reason(f"{kind}: something"), kind)

    def test_release_and_merge_lines_are_accepted(self) -> None:
        for subject in ("chore(main): release 0.35.0", "Merge branch 'main' into x", 'Revert "feat: x"', "Release 1.0"):
            self.assertIsNone(failure_reason(subject), subject)

    def test_an_untyped_subject_is_refused_with_the_shape_expected(self) -> None:
        reason = failure_reason("Add a workflow")
        self.assertIn('"Add a workflow" is not a Conventional Commit', reason)
        self.assertIn("feat(ci): add a workflow", reason)

    def test_an_unknown_type_is_refused(self) -> None:
        self.assertIsNotNone(failure_reason("feature: add a workflow"))

    def test_an_uppercase_scope_is_refused(self) -> None:
        self.assertIsNotNone(failure_reason("feat(CI): add a workflow"))

    def test_a_type_without_a_subject_is_refused(self) -> None:
        self.assertIsNotNone(failure_reason("feat: "))


class FindingAttribution(unittest.TestCase):
    def test_a_co_author_trailer_naming_an_agent_is_found(self) -> None:
        [finding] = attribution_findings("Co-Authored-By: Claude <noreply@anthropic.com>")
        self.assertIn('Co-Authored-By trailer names a coding agent ("claude")', finding)

    def test_a_human_co_author_is_not_found(self) -> None:
        self.assertEqual(attribution_findings("Co-authored-by: Jules Verne <jules@example.com>"), [])

    def test_a_generated_with_banner_naming_an_agent_is_found(self) -> None:
        [finding] = attribution_findings("🤖 Generated with Copilot")
        self.assertIn('"generated with" banner names a coding agent ("copilot")', finding)

    def test_a_generated_by_line_naming_no_agent_is_not_found(self) -> None:
        self.assertEqual(attribution_findings("Types generated by ogen from the OpenAPI file."), [])

    def test_a_session_link_is_found(self) -> None:
        [finding] = attribution_findings("See https://claude.ai/code/session_123 for the session.")
        self.assertIn("link back to a coding agent session", finding)

    def test_a_session_host_on_a_subdomain_is_found(self) -> None:
        self.assertEqual(len(attribution_findings("https://app.devin.ai/sessions/1")), 1)

    def test_a_session_host_inside_another_hosts_path_is_not_found(self) -> None:
        self.assertEqual(attribution_findings("https://example.com/claude.ai/x"), [])

    def test_a_host_one_character_off_is_not_found(self) -> None:
        self.assertEqual(attribution_findings("https://chatXopenai.com/"), [])

    def test_ordinary_text_is_not_found(self) -> None:
        self.assertEqual(attribution_findings("## Summary\n\nAdds a workflow.\n\n- one\n"), [])


class CheckingAPullRequest(unittest.TestCase):
    def test_a_clean_pull_request_has_no_failures(self) -> None:
        self.assertEqual(check("feat: x", "Body.", ["feat: x\n\nBody.", "fix: y"]), [])

    def test_each_failure_names_where_it_was_found(self) -> None:
        failures = check(
            "Add x",
            "Generated with Claude Code",
            ["wip", "fix: y\n\nCo-Authored-By: Codex <codex@openai.com>"],
        )
        self.assertEqual(len(failures), 4)
        self.assertTrue(failures[0].startswith("pull request title: "))
        self.assertTrue(failures[1].startswith("pull request body: "))
        self.assertTrue(failures[2].startswith('commit "wip": '))
        self.assertTrue(failures[3].startswith('commit "fix: y": a Co-Authored-By'))


class ReadingCommits(unittest.TestCase):
    def setUp(self) -> None:
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        self.cwd = os.getcwd()
        os.chdir(self.dir.name)
        self.addCleanup(os.chdir, self.cwd)

        def git(*args: str) -> None:
            subprocess.run(["git", *args], check=True, capture_output=True)

        git("init", "-q", "-b", "main")
        git("config", "user.email", "test@example.com")
        git("config", "user.name", "Test")
        git("commit", "-q", "--allow-empty", "-m", "chore: base")
        git("commit", "-q", "--allow-empty", "-m", "feat: one\n\nWith a body.\n\nAnd a blank line.")
        git("commit", "-q", "--allow-empty", "-m", "fix: two")

    def test_every_message_in_the_range_is_read_whole(self) -> None:
        self.assertEqual(
            commit_messages("HEAD~2..HEAD"),
            ["fix: two", "feat: one\n\nWith a body.\n\nAnd a blank line."],
        )

    def test_main_passes_a_clean_range(self) -> None:
        out = io.StringIO()
        with redirect_stdout(out):
            self.assertEqual(main(["--title", "feat: x", "--range", "HEAD~2..HEAD"]), 0)
        self.assertIn("2 commit(s)", out.getvalue())


class RunningTheCommand(unittest.TestCase):
    def test_failures_are_reported_as_error_annotations(self) -> None:
        out = io.StringIO()
        with redirect_stdout(out):
            self.assertEqual(main(["--title", "Add x"]), 1)
        self.assertTrue(out.getvalue().startswith("::error::pull request title: "))

    def test_title_and_body_are_read_from_the_environment(self) -> None:
        out = io.StringIO()
        env = {"PR_TITLE": "docs: x", "PR_BODY": "Generated with ChatGPT"}
        with mock.patch.dict(os.environ, env), redirect_stdout(out):
            self.assertEqual(main([]), 1)
        self.assertIn("pull request body: ", out.getvalue())

    def test_a_missing_title_is_a_usage_error(self) -> None:
        with mock.patch.dict(os.environ, {"PR_TITLE": ""}), redirect_stderr(io.StringIO()):
            with self.assertRaises(SystemExit) as raised:
                main([])
        self.assertEqual(raised.exception.code, 2)


if __name__ == "__main__":
    unittest.main()
